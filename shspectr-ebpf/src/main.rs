fn try_sys_exit_read(ctx: &TracePointContext) -> Result<(), i64> {
    let pid_tgid = bpf_get_current_pid_tgid();

    // SAFETY: PENDING_READ is a valid BPF hash map.
    let Some(pending) = (unsafe { PENDING_READ.get(&pid_tgid) }) else {
        return Ok(());
    };

    // SAFETY: ret is at offset 16 in sys_exit_read tracepoint args.
    let ret: i64 = unsafe { ctx.read_at(16).map_err(|_| 1i64)? };

    // Negative return means error — no data was read.
    if ret <= 0 {
        let _ = PENDING_READ.remove(&pid_tgid);
        return Ok(());
    }

    let bytes_read = ret as u64;
    let buf_ptr = pending.buf_ptr as *const u8;
    let fd = pending.fd;
    let tgid = (pid_tgid >> 32) as u32;
    // SAFETY: EXEC_PIDS is a valid BPF hash map.
    let Some(execution_id) = (unsafe { EXEC_PIDS.get(&tgid) }).copied() else {
        let _ = PENDING_READ.remove(&pid_tgid);
        return Ok(());
    };

    // Reserve ring buffer space and write event in-place.
    let Some(mut entry) = EVENTS.reserve::<IoEvent>(0) else {
        let _ = PENDING_READ.remove(&pid_tgid);
        return Err(1);
    };
    let event = entry.as_mut_ptr();

    // SAFETY: event points to reserved ringbuf memory with IoEvent layout.
    unsafe {
        core::ptr::write_bytes(event, 0u8, 1);
        let hdr = fill_header(EventType::Read, pid_tgid, execution_id);
        core::ptr::write(&raw mut (*event).header, hdr);
        core::ptr::write(&raw mut (*event).fd, fd);
        core::ptr::write(&raw mut (*event).count, bytes_read);
        if fill_io_data(event, buf_ptr, bytes_read).is_err() {
            entry.discard(0);
            let _ = PENDING_READ.remove(&pid_tgid);
            return Err(1);
        }
    }

    entry.submit(0);

    let _ = PENDING_READ.remove(&pid_tgid);

    Ok(())
}

#[panic_handler]
fn panic(_info: &core::panic::PanicInfo) -> ! {
    loop {}
}
